# ===============================
# Step 1: Imports
# ===============================
import torch
import torch.nn as nn
import torch.optim as optim
from torch.utils.data import DataLoader, Dataset
import numpy as np

# ===============================
# Step 2: Toy Text Dataset
# ===============================
sentences = [
    "i love deep learning",
    "autoencoders learn compression",
    "pytorch makes life easier",
    "neural networks are powerful",
    "machine learning is fun",
    "i enjoy training models",
    "latent space captures meaning",
    "text autoencoders use embeddings",
    "optimizers like adamw are popular",
    "data is the new oil"
]

# Tokenize (split by space)
tokenized = [s.split() for s in sentences]

# Build vocabulary
vocab = {"<pad>":0, "<bos>":1, "<eos>":2, "<unk>":3}
for sent in tokenized:
    for word in sent:
        if word not in vocab:
            vocab[word] = len(vocab)

inv_vocab = {v:k for k,v in vocab.items()}
vocab_size = len(vocab)
print("Vocab:", vocab)

# Encode function
def encode_sentence(sentence, max_len=10):
    tokens = ["<bos>"] + sentence.split() + ["<eos>"]
    ids = [vocab.get(tok, vocab["<unk>"]) for tok in tokens]
    if len(ids) < max_len:
        ids += [vocab["<pad>"]] * (max_len - len(ids))
    else:
        ids = ids[:max_len]
    return torch.tensor(ids)

# Dataset class
class TextDataset(Dataset):
    def __init__(self, sentences, max_len=10):
        self.data = [encode_sentence(s, max_len) for s in sentences]
    def __len__(self):
        return len(self.data)
    def __getitem__(self, idx):
        return self.data[idx]

dataset = TextDataset(sentences, max_len=12)
dataloader = DataLoader(dataset, batch_size=2, shuffle=True)

# ===============================
# Step 3: Text Autoencoder Model
# ===============================
class TextAutoencoder(nn.Module):
    def __init__(self, vocab_size, embed_dim=64, hidden_dim=128, latent_dim=32):
        super(TextAutoencoder, self).__init__()
        self.embedding = nn.Embedding(vocab_size, embed_dim, padding_idx=vocab["<pad>"])

        # Encoder
        self.encoder_lstm = nn.LSTM(embed_dim, hidden_dim, batch_first=True)
        self.hidden_to_latent = nn.Linear(hidden_dim, latent_dim)

        # Decoder
        self.latent_to_hidden = nn.Linear(latent_dim, hidden_dim)
        self.decoder_lstm = nn.LSTM(embed_dim, hidden_dim, batch_first=True)
        self.output_layer = nn.Linear(hidden_dim, vocab_size)

    def encode(self, x):
        embedded = self.embedding(x)
        _, (h, _) = self.encoder_lstm(embedded)
        z = self.hidden_to_latent(h[-1])
        return z

    def decode(self, z, x):
        hidden = torch.tanh(self.latent_to_hidden(z)).unsqueeze(0)
        cell = torch.zeros_like(hidden)
        embedded = self.embedding(x)
        output, _ = self.decoder_lstm(embedded, (hidden, cell))
        logits = self.output_layer(output)
        return logits

    def forward(self, x):
        z = self.encode(x)
        logits = self.decode(z, x)
        return logits

# ===============================
# Step 4: Training Setup
# ===============================
device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
model = TextAutoencoder(vocab_size).to(device)

criterion = nn.CrossEntropyLoss(ignore_index=vocab["<pad>"])
optimizer = optim.AdamW(model.parameters(), lr=1e-3)

# ===============================
# Step 5: Training Loop
# ===============================
epochs = 30
for epoch in range(epochs):
    total_loss = 0
    for batch in dataloader:
        batch = batch.to(device)
        optimizer.zero_grad()
        outputs = model(batch)

        # Reshape for loss
        loss = criterion(outputs.view(-1, vocab_size), batch.view(-1))
        loss.backward()
        optimizer.step()

        total_loss += loss.item()
    print(f"Epoch [{epoch+1}/{epochs}], Loss: {total_loss/len(dataloader):.4f}")

# ===============================
# Step 6: Test Reconstruction
# ===============================
def reconstruct_sentence(model, sentence):
    model.eval()
    x = encode_sentence(sentence, max_len=12).unsqueeze(0).to(device)
    with torch.no_grad():
        logits = model(x)
        pred = logits.argmax(-1).squeeze().cpu().numpy()
    decoded = [inv_vocab[idx] for idx in pred if idx != vocab["<pad>"]]
    return " ".join(decoded)

test_sentence = "i love deep learning"
print("Original:", test_sentence)
print("Reconstructed:", reconstruct_sentence(model, test_sentence))