# ===== ConvVAE with KL Annealing for MNIST =====
import torch
import torch.nn as nn
import torch.nn.functional as F
import torch.optim as optim
from torchvision import datasets, transforms
from torch.utils.data import DataLoader
import matplotlib.pyplot as plt

# -----------------------------
# Config
# -----------------------------
batch_size = 128
latent_dim = 16
epochs = 15
device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
print("Using device:", device)

# -----------------------------
# Data (MNIST)
# -----------------------------
transform = transforms.Compose([
    transforms.ToTensor(),   # converts to [0,1]
])

train_loader = DataLoader(
    datasets.MNIST("./data", train=True, download=True, transform=transform),
    batch_size=batch_size, shuffle=True
)

test_loader = DataLoader(
    datasets.MNIST("./data", train=False, download=True, transform=transform),
    batch_size=batch_size, shuffle=True
)

# -----------------------------
# ConvVAE Model
# -----------------------------
class ConvVAE(nn.Module):
    def __init__(self, latent_dim=16):
        super().__init__()
        # Encoder
        self.enc = nn.Sequential(
            nn.Conv2d(1, 32, 4, 2, 1), nn.ReLU(),   # 28x28 -> 14x14
            nn.Conv2d(32, 64, 4, 2, 1), nn.ReLU()   # 14x14 -> 7x7
        )
        self.enc_flat = 64 * 7 * 7
        self.fc_mu = nn.Linear(self.enc_flat, latent_dim)
        self.fc_logvar = nn.Linear(self.enc_flat, latent_dim)

        # Decoder
        self.fc_dec = nn.Linear(latent_dim, self.enc_flat)
        self.dec = nn.Sequential(
            nn.ConvTranspose2d(64, 32, 4, 2, 1), nn.ReLU(),   # 7x7 -> 14x14
            nn.ConvTranspose2d(32, 1, 4, 2, 1), nn.Sigmoid()  # 14x14 -> 28x28
        )

    def encode(self, x):
        h = self.enc(x).view(-1, self.enc_flat)
        mu, logvar = self.fc_mu(h), self.fc_logvar(h)
        return mu, logvar

    def reparameterize(self, mu, logvar):
        std = torch.exp(0.5 * logvar)
        eps = torch.randn_like(std)
        return mu + eps * std

    def decode(self, z):
        h = self.fc_dec(z).view(-1, 64, 7, 7)
        return self.dec(h)

    def forward(self, x):
        mu, logvar = self.encode(x)
        z = self.reparameterize(mu, logvar)
        recon = self.decode(z)
        return recon, mu, logvar

# -----------------------------
# Loss Function
# -----------------------------
def loss_fn(recon_x, x, mu, logvar, beta):
    # Flatten for BCE
    x = x.view(x.size(0), -1)
    recon_x = recon_x.view(x.size(0), -1)

    # Reconstruction Loss
    recon_loss = F.binary_cross_entropy(recon_x, x, reduction="sum") / x.size(0)

    # KL Divergence
    kl_loss = -0.5 * torch.sum(1 + logvar - mu.pow(2) - logvar.exp()) / x.size(0)

    return recon_loss + beta * kl_loss, recon_loss, kl_loss

# -----------------------------
# Training Loop
# -----------------------------
model = ConvVAE(latent_dim=latent_dim).to(device)
optimizer = optim.Adam(model.parameters(), lr=1e-3)

for epoch in range(1, epochs + 1):
    model.train()
    total_loss, total_recon, total_kl = 0, 0, 0
    beta = min(1.0, epoch / 10)  # KL warm-up

    for data, _ in train_loader:
        data = data.to(device)
        optimizer.zero_grad()
        recon, mu, logvar = model(data)
        loss, recon_loss, kl_loss = loss_fn(recon, data, mu, logvar, beta)
        loss.backward()
        optimizer.step()

        total_loss += loss.item()
        total_recon += recon_loss.item()
        total_kl += kl_loss.item()

    print(f"Epoch {epoch}/{epochs} | "
          f"Loss={total_loss/len(train_loader):.4f} "
          f"Recon={total_recon/len(train_loader):.4f} "
          f"KL={total_kl/len(train_loader):.4f} "
          f"Beta={beta:.2f}")

# -----------------------------
# Reconstructions
# -----------------------------
model.eval()
with torch.no_grad():
    data, _ = next(iter(test_loader))
    data = data.to(device)
    recon, _, _ = model(data)

    fig, axes = plt.subplots(2, 8, figsize=(12, 4))
    for i in range(8):
        axes[0, i].imshow(data[i].cpu().squeeze(), cmap="gray")
        axes[0, i].axis("off")
        axes[1, i].imshow(recon[i].cpu().squeeze(), cmap="gray")
        axes[1, i].axis("off")
    axes[0, 0].set_title("Original")
    axes[1, 0].set_title("Recon")
    plt.show()

# -----------------------------
# Random Samples
# -----------------------------
with torch.no_grad():
    z = torch.randn(8, latent_dim).to(device)
    samples = model.decode(z)
    fig, axes = plt.subplots(1, 8, figsize=(12, 2))
    for i in range(8):
        axes[i].imshow(samples[i].cpu().squeeze(), cmap="gray")
        axes[i].axis("off")
    plt.show()