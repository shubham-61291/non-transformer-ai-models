# =========================
# DCGAN on MNIST ( + Loss Plots)
# =========================
import torch
import torch.nn as nn
import torch.optim as optim
from torchvision import datasets, transforms
from torch.utils.data import DataLoader
import matplotlib.pyplot as plt

# -----------------------------
# Config
# -----------------------------
batch_size = 128
z_dim = 100
epochs = 20
lr = 2e-4
betas = (0.5, 0.999)
device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
print("Using device:", device)

# -----------------------------
# Data (MNIST to [-1,1])
# -----------------------------
transform = transforms.Compose([
    transforms.Resize(28),
    transforms.ToTensor(),
    transforms.Normalize((0.5,), (0.5,))  # [-1, 1]
])

train_loader = DataLoader(
    datasets.MNIST("./data", train=True, download=True, transform=transform),
    batch_size=batch_size, shuffle=True
)

# -----------------------------
# Weights init (DCGAN style)
# -----------------------------
def weights_init(m):
    if isinstance(m, (nn.Conv2d, nn.ConvTranspose2d, nn.Linear, nn.BatchNorm2d)):
        if hasattr(m, "weight") and m.weight is not None:
            nn.init.normal_(m.weight, 0.0, 0.02)
        if hasattr(m, "bias") and m.bias is not None:
            nn.init.zeros_(m.bias)

# -----------------------------
# Generator: z -> 7x7 -> 14x14 -> 28x28
# -----------------------------
class Generator(nn.Module):
    def __init__(self, z_dim=100, img_channels=1, base=64):
        super().__init__()
        self.proj = nn.Sequential(
            nn.Linear(z_dim, 256 * 7 * 7),
            nn.ReLU(True),
        )
        self.up = nn.Sequential(
            # 256 x 7 x 7 -> 128 x 14 x 14
            nn.ConvTranspose2d(256, 128, 4, 2, 1, bias=False),
            nn.BatchNorm2d(128),
            nn.ReLU(True),
            # 128 x 14 x 14 -> 64 x 28 x 28
            nn.ConvTranspose2d(128, 64, 4, 2, 1, bias=False),
            nn.BatchNorm2d(64),
            nn.ReLU(True),
            # 64 x 28 x 28 -> 1 x 28 x 28
            nn.Conv2d(64, img_channels, 3, 1, 1, bias=False),
            nn.Tanh()
        )

    def forward(self, z):
        x = self.proj(z)                          # [B, 256*7*7]
        x = x.view(z.size(0), 256, 7, 7)          # [B, 256, 7, 7]
        x = self.up(x)                            # [B, 1, 28, 28]
        return x

# -----------------------------
# Discriminator: 28 -> 14 -> 7 -> 1
# -----------------------------
class Discriminator(nn.Module):
    def __init__(self, img_channels=1):
        super().__init__()
        self.net = nn.Sequential(
            # 1 x 28 x 28 -> 64 x 14 x 14
            nn.Conv2d(img_channels, 64, 4, 2, 1, bias=False),
            nn.LeakyReLU(0.2, inplace=True),
            # 64 x 14 x 14 -> 128 x 7 x 7
            nn.Conv2d(64, 128, 4, 2, 1, bias=False),
            nn.BatchNorm2d(128),
            nn.LeakyReLU(0.2, inplace=True),
            # 128 x 7 x 7 -> 1 x 1 x 1  (kernel=7 collapses exactly)
            nn.Conv2d(128, 1, 7, 1, 0, bias=False),
            nn.Sigmoid()
        )

    def forward(self, x):
        out = self.net(x)                         # [B, 1, 1, 1]
        return out.view(-1, 1)                    # [B, 1]

G = Generator(z_dim=z_dim).to(device)
D = Discriminator().to(device)
G.apply(weights_init)
D.apply(weights_init)

# -----------------------------
# Loss & Optimizers
# -----------------------------
criterion = nn.BCELoss()
opt_G = optim.Adam(G.parameters(), lr=lr, betas=betas)
opt_D = optim.Adam(D.parameters(), lr=lr, betas=betas)

# -----------------------------
# Training
# -----------------------------
fixed_noise = torch.randn(16, z_dim, device=device)
losses_D, losses_G = [], []

for epoch in range(1, epochs + 1):
    D_epoch, G_epoch, n_batches = 0.0, 0.0, 0

    for real, _ in train_loader:
        real = real.to(device)
        bsz = real.size(0)
        n_batches += 1

        real_labels = torch.ones(bsz, 1, device=device)
        fake_labels = torch.zeros(bsz, 1, device=device)

        # ---- Train D ----
        z = torch.randn(bsz, z_dim, device=device)
        fake = G(z).detach()

        D_real = D(real)
        D_fake = D(fake)

        loss_D_real = criterion(D_real, real_labels)
        loss_D_fake = criterion(D_fake, fake_labels)
        loss_D = loss_D_real + loss_D_fake

        opt_D.zero_grad()
        loss_D.backward()
        opt_D.step()

        # ---- Train G ----
        z = torch.randn(bsz, z_dim, device=device)
        fake = G(z)
        D_fake = D(fake)
        loss_G = criterion(D_fake, real_labels)   # want D(fake)=1

        opt_G.zero_grad()
        loss_G.backward()
        opt_G.step()

        D_epoch += loss_D.item()
        G_epoch += loss_G.item()

    losses_D.append(D_epoch / n_batches)
    losses_G.append(G_epoch / n_batches)
    print(f"Epoch {epoch}/{epochs} | Loss_D={losses_D[-1]:.4f} | Loss_G={losses_G[-1]:.4f}")

    # sample grid every 5 epochs
    if epoch % 5 == 0:
        with torch.no_grad():
            samples = G(fixed_noise).cpu()
            samples = (samples + 1) / 2.0  # [-1,1] -> [0,1]
            fig, axes = plt.subplots(2, 8, figsize=(12, 3))
            for i in range(16):
                ax = axes[i // 8, i % 8]
                ax.imshow(samples[i, 0], cmap="gray")
                ax.axis("off")
            plt.show()

# -----------------------------
# Plot losses
# -----------------------------
plt.figure(figsize=(8, 5))
plt.plot(losses_D, label="Discriminator Loss")
plt.plot(losses_G, label="Generator Loss")
plt.xlabel("Epoch")
plt.ylabel("Loss")
plt.title("DCGAN Training Losses")
plt.legend()
plt.show()