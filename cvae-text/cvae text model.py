# =========================
# Text CVAE (Conditional VAE for Text)
# =========================
import torch
import torch.nn as nn
import torch.optim as optim
from torch.utils.data import DataLoader, Dataset
import re

device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
print("Device:", device)

# ---------- Toy Corpus with labels ----------
# labels: 0 = neutral, 1 = positive, 2 = negative
sentences = [
    ("i love deep learning", 0),
    ("autoencoders are cool", 0),
    ("this movie was great", 1),
    ("that film was terrible", 2),
    ("i like machine learning", 0),
    ("this movie was boring", 2),
    ("an excellent performance", 1),
    ("a very bad script", 2),
]
num_classes = 3

def tok(x):
    return re.findall(r"\b\w+\b", x.lower())

PAD, BOS, EOS, UNK = "<pad>", "<bos>", "<eos>", "<unk>"
vocab = {PAD:0, BOS:1, EOS:2, UNK:3}
for s,_ in sentences:
    for w in tok(s):
        if w not in vocab:
            vocab[w] = len(vocab)
ivocab = {i:w for w,i in vocab.items()}

pad_idx, bos_idx, eos_idx = vocab[PAD], vocab[BOS], vocab[EOS]
V = len(vocab)
MAX_LEN = 10

def encode_with_bos_eos(s):
    ids = [bos_idx] + [vocab.get(w,3) for w in tok(s)] + [eos_idx]
    ids = ids[:MAX_LEN]
    ids += [pad_idx]*(MAX_LEN - len(ids))
    return ids

data = [(encode_with_bos_eos(s), y) for s,y in sentences]

class TextDataset(Dataset):
    def __init__(self, data):
        self.x = torch.tensor([d[0] for d in data], dtype=torch.long)
        self.y = torch.tensor([d[1] for d in data], dtype=torch.long)
    def __len__(self): return len(self.x)
    def __getitem__(self,i): return self.x[i], self.y[i]

loader = DataLoader(TextDataset(data), batch_size=2, shuffle=True)

# ---------- Model ----------
class TextCVAE(nn.Module):
    def __init__(self, vocab_size, num_classes, emb=64, hid=128, lat=16):
        super().__init__()
        self.emb = nn.Embedding(vocab_size, emb, padding_idx=pad_idx)
        self.label_emb = nn.Embedding(num_classes, emb)

        # Encoder
        self.enc_rnn = nn.LSTM(emb, hid, batch_first=True)
        self.fc_mu = nn.Linear(hid + emb, lat)
        self.fc_lv = nn.Linear(hid + emb, lat)

        # Decoder
        self.lat2hid = nn.Linear(lat + emb, hid)
        self.dec_rnn = nn.LSTM(emb, hid, batch_first=True)
        self.out = nn.Linear(hid, vocab_size)

    def encode(self, x, y):
        e = self.emb(x)                          # [B,T,emb]
        _, (h, c) = self.enc_rnn(e)
        h = h[-1]                                # [B,hid]
        y_emb = self.label_emb(y)                # [B,emb]
        hy = torch.cat([h, y_emb], dim=1)
        mu, lv = self.fc_mu(hy), self.fc_lv(hy)
        return mu, lv

    def reparam(self, mu, lv):
        std = torch.exp(0.5*lv)
        eps = torch.randn_like(std)
        return mu + eps*std

    def decode_teacher_forced(self, z, y, x_in):
        y_emb = self.label_emb(y)
        zy = torch.cat([z, y_emb], dim=1)
        h0 = torch.tanh(self.lat2hid(zy)).unsqueeze(0)
        c0 = torch.zeros_like(h0)
        e = self.emb(x_in)
        dec_out, _ = self.dec_rnn(e, (h0,c0))
        return self.out(dec_out)

    def forward(self, x, y):
        mu, lv = self.encode(x,y)
        z = self.reparam(mu,lv)
        dec_in, target = x[:,:-1], x[:,1:]
        logits = self.decode_teacher_forced(z,y,dec_in)
        return logits, target, mu, lv

# ---------- Loss ----------
ce = nn.CrossEntropyLoss(ignore_index=pad_idx)
def vae_loss(logits, targets, mu, lv, beta=1.0):
    B,T,V = logits.shape
    rec = ce(logits.reshape(-1,V), targets.reshape(-1))
    kld = -0.5*torch.mean(1 + lv - mu.pow(2) - lv.exp())
    return rec + beta*kld, rec.detach(), kld.detach()

# ---------- Train ----------
model = TextCVAE(V, num_classes).to(device)
opt = optim.Adam(model.parameters(), lr=1e-3)
epochs=50

for ep in range(1, epochs+1):
    model.train()
    beta = min(1.0, ep/10)
    tot=rec_tot=kld_tot=0.0
    for x,y in loader:
        x,y = x.to(device), y.to(device)
        opt.zero_grad()
        logits, targets, mu, lv = model(x,y)
        loss, rec, kld = vae_loss(logits, targets, mu, lv, beta)
        loss.backward(); opt.step()
        tot+=loss.item(); rec_tot+=rec.item(); kld_tot+=kld.item()
    n=len(loader)
    print(f"Epoch {ep:02d}/{epochs} | beta={beta:.2f} | Loss {tot/n:.3f} Rec {rec_tot/n:.3f} KL {kld_tot/n:.3f}")

# ---------- Helpers ----------
def decode_ids(ids):
    toks=[]
    for i in ids:
        if i==pad_idx: continue
        if i==eos_idx: break
        if i==bos_idx: continue
        toks.append(ivocab.get(int(i), "<unk>"))
    return " ".join(toks)

# ---------- Reconstructions ----------
print("\n=== Reconstructions with Labels ===")
model.eval()
with torch.no_grad():
    for x,y in loader:
        x,y = x.to(device), y.to(device)
        logits, targets, mu, lv = model(x,y)
        pred = logits.argmax(-1)  # greedy
        pred_full = torch.cat([torch.full((pred.size(0),1), bos_idx, device=device), pred], dim=1)
        for inp,out,lbl in zip(x.cpu(), pred_full.cpu(), y.cpu()):
            print(f"Label {lbl.item()} | Input:      {decode_ids(inp.tolist())}")
            print(f"Label {lbl.item()} | Reconstruct:{decode_ids(out.tolist())}")
            print("-"*60)
        break  # print only first batch

# ---------- Random Generations ----------
print("\n=== Random Generations (conditioned on label) ===")
with torch.no_grad():
    for y_val in range(num_classes):
        y_t = torch.tensor([y_val],device=device)
        z = torch.randn(1,16,device=device)
        y_emb = model.label_emb(y_t)
        zy = torch.cat([z,y_emb],dim=1)
        h0 = torch.tanh(model.lat2hid(zy)).unsqueeze(0)
        c0 = torch.zeros_like(h0)
        inp = torch.full((1,1), bos_idx, dtype=torch.long, device=device)
        outs=[]
        for _ in range(MAX_LEN-1):
            e = model.emb(inp)
            o,(h0,c0) = model.dec_rnn(e,(h0,c0))
            logits = model.out(o[:,-1,:])
            nxt = torch.argmax(logits,dim=-1,keepdim=True)
            outs.append(nxt)
            inp=nxt
        gen=torch.cat(outs,dim=1)
        print(f"Label {y_val}: {decode_ids(gen.squeeze(0).tolist())}")