# =========================
import torch
import torch.nn as nn
import torch.optim as optim
from torch.utils.data import DataLoader, Dataset
import re, random
device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
print("Device:", device)

# ---------- Toy corpus ----------
sentences = [
    "i love deep learning",
    "autoencoders are cool",
    "variational autoencoders generate data",
    "i like machine learning",
    "neural networks are powerful",
    "vae learns latent space",
    "reconstruction is the goal",
    "unsupervised learning is fun",
    "vae is probabilistic",
    "we train with kl divergence",
    "latent representations capture meaning",
    "models improve with more data",
    "optimization uses gradients",
    "adamw works well in practice",
    "regularization prevents overfitting",
]

def tok(x):
    x = x.lower()
    return re.findall(r"\b\w+\b", x)

# Build vocab with specials
PAD, BOS, EOS, UNK = "<pad>", "<bos>", "<eos>", "<unk>"
vocab = {PAD:0, BOS:1, EOS:2, UNK:3}
for s in sentences:
    for w in tok(s):
        if w not in vocab:
            vocab[w] = len(vocab)
ivocab = {i:w for w,i in vocab.items()}
pad_idx, bos_idx, eos_idx, unk_idx = vocab[PAD], vocab[BOS], vocab[EOS], vocab[UNK]
V = len(vocab)
print("Vocab size:", V)

MAX_LEN = 12  # includes BOS/EOS

def encode_with_bos_eos(s, max_len=MAX_LEN):
    ids = [bos_idx] + [vocab.get(w, unk_idx) for w in tok(s)] + [eos_idx]
    ids = ids[:max_len]
    ids += [pad_idx]*(max_len - len(ids))
    return ids

data = [encode_with_bos_eos(s) for s in sentences]

class TextDataset(Dataset):
    def __init__(self, data):
        self.data = torch.tensor(data, dtype=torch.long)
    def __len__(self): return len(self.data)
    def __getitem__(self, i): return self.data[i]

ds = TextDataset(data)
loader = DataLoader(ds, batch_size=4, shuffle=True)

# ---------- Model ----------
class TextVAE(nn.Module):
    def __init__(self, vocab_size, emb=64, hid=128, lat=16):
        super().__init__()
        self.emb = nn.Embedding(vocab_size, emb, padding_idx=pad_idx)

        # encoder
        self.enc_rnn = nn.LSTM(emb, hid, batch_first=True)
        self.fc_mu = nn.Linear(hid, lat)
        self.fc_lv = nn.Linear(hid, lat)

        # decoder
        self.lat2hid = nn.Linear(lat, hid)
        self.dec_rnn = nn.LSTM(emb, hid, batch_first=True)
        self.out = nn.Linear(hid, vocab_size)

    def encode(self, x):
        # x: [B, T] (with BOS...EOS)
        e = self.emb(x)
        _, (h, c) = self.enc_rnn(e)
        h = h[-1]  # [B, hid]
        mu, lv = self.fc_mu(h), self.fc_lv(h)
        return mu, lv

    def reparam(self, mu, lv):
        std = torch.exp(0.5*lv)
        eps = torch.randn_like(std)
        return mu + eps*std

    def decode_teacher_forced(self, z, x_in):
        """
        Teacher forcing: feed ground-truth tokens (shifted left).
        x_in: decoder inputs = [BOS, w1, w2, ..., w_{T-1}]
        target later will be [w1, w2, ..., EOS]
        """
        h0 = torch.tanh(self.lat2hid(z)).unsqueeze(0)  # [1,B,hid]
        c0 = torch.zeros_like(h0)
        e = self.emb(x_in)                             # [B,T-1,emb]
        dec_out, _ = self.dec_rnn(e, (h0, c0))         # [B,T-1,hid]
        logits = self.out(dec_out)                     # [B,T-1,V]
        return logits

    def decode_greedy(self, z, max_len=MAX_LEN, temperature=1.0):
        h = torch.tanh(self.lat2hid(z)).unsqueeze(0)
        c = torch.zeros_like(h)
        inp = torch.full((z.size(0), 1), bos_idx, dtype=torch.long, device=z.device)
        outs = []
        for _ in range(max_len-1):
            e = self.emb(inp)
            o, (h,c) = self.dec_rnn(e, (h,c))
            logits = self.out(o[:, -1, :]) / temperature
            next_tok = torch.argmax(logits, dim=-1, keepdim=True)
            outs.append(next_tok)
            inp = next_tok
        return torch.cat(outs, dim=1)  # [B, T-1]

    def forward(self, x):
        mu, lv = self.encode(x)
        z = self.reparam(mu, lv)
        # prepare decoder inputs/targets (teacher forcing)
        # x = [BOS, w1, w2, ..., EOS, PAD...]
        dec_in  = x[:, :-1]        # drop last token
        target  = x[:, 1:]         # drop first (shifted)
        logits  = self.decode_teacher_forced(z, dec_in)
        return logits, target, mu, lv

model = TextVAE(V).to(device)

# ---------- Loss & Optim ----------
ce = nn.CrossEntropyLoss(ignore_index=pad_idx)  # over vocab
def vae_loss(logits, targets, mu, lv, beta=1.0):
    # logits: [B, T-1, V]; targets: [B, T-1]
    B, Tm1, Vv = logits.shape
    rec = ce(logits.reshape(-1, Vv), targets.reshape(-1))
    kld = -0.5 * torch.mean(1 + lv - mu.pow(2) - lv.exp())
    return rec + beta*kld, rec.detach(), kld.detach()

opt = optim.AdamW(model.parameters(), lr=1e-3, weight_decay=1e-4)
clip = 1.0

# ---------- Train with KL annealing & teacher forcing ----------
epochs = 150
for ep in range(1, epochs+1):
    model.train()
    beta = min(1.0, ep/15.0)  # warm up KL over first ~15 epochs
    tot=rec_tot=kld_tot=0.0
    for batch in loader:
        x = batch.to(device)
        opt.zero_grad()
        logits, targets, mu, lv = model(x)
        loss, rec, kld = vae_loss(logits, targets, mu, lv, beta)
        loss.backward()
        nn.utils.clip_grad_norm_(model.parameters(), clip)
        opt.step()
        tot += loss.item(); rec_tot += rec.item(); kld_tot += kld.item()
    n=len(loader)
    print(f"Epoch {ep:02d}/{epochs} | beta={beta:.2f} | Loss {tot/n:.3f}  Rec {rec_tot/n:.3f}  KL {kld_tot/n:.3f}")

# ---------- Helpers ----------
def decode_ids(ids):
    toks=[]
    for i in ids:
        if i==pad_idx: continue
        if i==eos_idx: break
        if i==bos_idx: continue
        toks.append(ivocab.get(int(i), "<unk>"))
    return " ".join(toks)

# ---------- Reconstructions ----------
model.eval()
print("\n=== Reconstructions ===")
with torch.no_grad():
    for batch in loader:
        x = batch.to(device)
        logits, targets, mu, lv = model(x)
        pred = logits.argmax(-1)  # [B, T-1]
        # shift back to align to full length for printing
        # prepend BOS just for viewing
        pred_full = torch.cat([torch.full((pred.size(0),1), bos_idx, device=pred.device), pred], dim=1)
        for inp, out in zip(x.cpu(), pred_full.cpu()):
            print("Input:      ", decode_ids(inp.tolist()))
            print("Reconstruct:", decode_ids(out.tolist()))
            print("-"*40)
        break

# ---------- Random generations ----------
print("\n=== Random Generations ===")
with torch.no_grad():
    for _ in range(5):
        z = torch.randn(1, 16, device=device)
        gen = model.decode_greedy(z, max_len=MAX_LEN)   # [1, T-1]
        gen_full = torch.cat([torch.full((1,1), bos_idx, device=device), gen], dim=1)
        print("Generated:", decode_ids(gen_full.squeeze(0).tolist()))