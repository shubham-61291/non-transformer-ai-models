# ====== CVAE (Conv) for MNIST with label conditioning ======
import torch
import torch.nn as nn
import torch.nn.functional as F
import torch.optim as optim
from torchvision import datasets, transforms
from torch.utils.data import DataLoader
import matplotlib.pyplot as plt

# -----------------------------
# Config
# -----------------------------
batch_size = 128
latent_dim = 16
epochs = 15
num_classes = 10
lr = 1e-3
beta_warmup_epochs = 10
device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
print("Using device:", device)

# -----------------------------
# Data (MNIST)
# -----------------------------
transform = transforms.Compose([
    transforms.ToTensor(),  # [0,1]
])

train_loader = DataLoader(
    datasets.MNIST("./data", train=True, download=True, transform=transform),
    batch_size=batch_size, shuffle=True
)

test_loader = DataLoader(
    datasets.MNIST("./data", train=False, download=True, transform=transform),
    batch_size=batch_size, shuffle=True
)

# -----------------------------
# Utils
# -----------------------------
def one_hot(labels, num_classes=10, device="cpu"):
    """Convert label tensor [B] -> one-hot [B, num_classes]."""
    y = torch.zeros(labels.size(0), num_classes, device=device)
    y.scatter_(1, labels.view(-1,1), 1.0)
    return y

# -----------------------------
# CVAE Model (Conv)
#   Encoder: x -> conv -> flatten -> concat one-hot y -> (mu, logvar)
#   Decoder: concat z with one-hot y -> fc -> deconv -> x_hat
# -----------------------------
class ConvCVAE(nn.Module):
    def __init__(self, latent_dim=16, num_classes=10):
        super().__init__()
        self.latent_dim = latent_dim
        self.num_classes = num_classes

        # Encoder (Conv)
        self.enc = nn.Sequential(
            nn.Conv2d(1, 32, kernel_size=4, stride=2, padding=1),  # 28x28 -> 14x14
            nn.ReLU(inplace=True),
            nn.Conv2d(32, 64, kernel_size=4, stride=2, padding=1), # 14x14 -> 7x7
            nn.ReLU(inplace=True),
        )
        self.enc_flat = 64 * 7 * 7  # flatten size after convs

        # After flatten, concatenate label one-hot: [enc_flat + num_classes]
        self.fc_mu    = nn.Linear(self.enc_flat + num_classes, latent_dim)
        self.fc_logvar= nn.Linear(self.enc_flat + num_classes, latent_dim)

        # Decoder: take [z + one-hot] -> fc -> reshape -> deconv
        self.fc_dec = nn.Linear(latent_dim + num_classes, self.enc_flat)
        self.dec = nn.Sequential(
            nn.ConvTranspose2d(64, 32, kernel_size=4, stride=2, padding=1), # 7x7 -> 14x14
            nn.ReLU(inplace=True),
            nn.ConvTranspose2d(32, 1, kernel_size=4, stride=2, padding=1), # 14x14 -> 28x28
            nn.Sigmoid(),  # pixel probs
        )

    def encode(self, x, y_onehot):
        h = self.enc(x).view(-1, self.enc_flat)             # [B, enc_flat]
        hy = torch.cat([h, y_onehot], dim=1)                # [B, enc_flat + C]
        mu, logvar = self.fc_mu(hy), self.fc_logvar(hy)     # [B, Z], [B, Z]
        return mu, logvar

    def reparameterize(self, mu, logvar):
        std = torch.exp(0.5 * logvar)
        eps = torch.randn_like(std)
        return mu + eps * std

    def decode(self, z, y_onehot):
        zy = torch.cat([z, y_onehot], dim=1)                # [B, Z + C]
        h = self.fc_dec(zy).view(-1, 64, 7, 7)              # [B, 64, 7, 7]
        x_hat = self.dec(h)                                  # [B, 1, 28, 28]
        return x_hat

    def forward(self, x, y):
        y_oh = one_hot(y, self.num_classes, device=x.device)
        mu, logvar = self.encode(x, y_oh)
        z = self.reparameterize(mu, logvar)
        x_hat = self.decode(z, y_oh)
        return x_hat, mu, logvar

# -----------------------------
# Loss (BCE recon + beta * KL)
# -----------------------------
def loss_fn(recon_x, x, mu, logvar, beta=1.0):
    # BCE over pixels
    bce = F.binary_cross_entropy(recon_x, x, reduction="sum") / x.size(0)
    # KL (per batch average)
    kld = -0.5 * torch.sum(1 + logvar - mu.pow(2) - logvar.exp()) / x.size(0)
    return bce + beta * kld, bce, kld

# -----------------------------
# Train
# -----------------------------
model = ConvCVAE(latent_dim=latent_dim, num_classes=num_classes).to(device)
optimizer = optim.Adam(model.parameters(), lr=lr)

for epoch in range(1, epochs + 1):
    model.train()
    total, total_rec, total_kl = 0.0, 0.0, 0.0
    beta = min(1.0, epoch / beta_warmup_epochs)  # KL warm-up

    for data, labels in train_loader:
        data, labels = data.to(device), labels.to(device)
        optimizer.zero_grad()
        recon, mu, logvar = model(data, labels)
        loss, rec, kld = loss_fn(recon, data, mu, logvar, beta)
        loss.backward()
        optimizer.step()

        total += loss.item()
        total_rec += rec.item()
        total_kl += kld.item()

    n_batches = len(train_loader)
    print(f"Epoch {epoch}/{epochs} | Loss={total/n_batches:.4f} "
          f"Recon={total_rec/n_batches:.4f} KL={total_kl/n_batches:.4f} Beta={beta:.2f}")

# -----------------------------
# Reconstructions (condition matches true label)
# -----------------------------
model.eval()
with torch.no_grad():
    imgs, labels = next(iter(test_loader))
    imgs, labels = imgs.to(device), labels.to(device)
    recon, _, _ = model(imgs, labels)

    k = 8
    fig, axes = plt.subplots(2, k, figsize=(12, 4))
    for i in range(k):
        axes[0, i].imshow(imgs[i].cpu().squeeze(), cmap="gray")
        axes[0, i].set_title(f"y={labels[i].item()}")
        axes[0, i].axis("off")

        axes[1, i].imshow(recon[i].cpu().squeeze(), cmap="gray")
        axes[1, i].set_title("recon")
        axes[1, i].axis("off")
    plt.tight_layout()
    plt.show()

# -----------------------------
# Class-conditional random samples
#   For each label 0..9, sample z ~ N(0,I), decode(z, y)
# -----------------------------
with torch.no_grad():
    n_per_class = 8
    fig, axes = plt.subplots(num_classes, n_per_class, figsize=(12, 12))
    for cls in range(num_classes):
        y = torch.full((n_per_class,), cls, dtype=torch.long, device=device)
        y_oh = one_hot(y, num_classes, device=device)
        z = torch.randn(n_per_class, latent_dim, device=device)
        samples = model.decode(z, y_oh)  # [B,1,28,28]
        for j in range(n_per_class):
            axes[cls, j].imshow(samples[j].cpu().squeeze(), cmap="gray")
            axes[cls, j].axis("off")
        axes[cls, 0].set_ylabel(f"y={cls}", rotation=0, labelpad=25, fontsize=10)
    plt.tight_layout()
    plt.show()