# -----------------------------
# 2) Vocab & helpers
# -----------------------------
PAD, MASK = "<pad>", "<mask>"
words = sorted(set(w for s in sentences for w in s.split()))
vocab = [PAD, MASK] + words
stoi = {w:i for i,w in enumerate(vocab)}
itos = {i:w for w,i in stoi.items()}
pad_idx, mask_idx = stoi[PAD], stoi[MASK]
V = len(vocab)

def encode(s): return [stoi[w] for w in s.split()]
def decode(ids): return " ".join(itos[i] for i in ids if i != pad_idx)

data = [encode(s) for s in sentences]
MAX_LEN = max(len(x) for x in data)

class TextSet(Dataset):
    def __init__(self, seqs): self.seqs = seqs
    def __len__(self): return len(self.seqs)
    def __getitem__(self, i): return torch.tensor(self.seqs[i], dtype=torch.long)

def collate(batch):
    # pad to MAX_LEN
    B = len(batch)
    out = torch.full((B, MAX_LEN), pad_idx, dtype=torch.long)
    for i, seq in enumerate(batch):
        out[i, :len(seq)] = seq
    return out

ds = TextSet(data)
loader = DataLoader(ds, batch_size=32, shuffle=True, collate_fn=collate)

# -----------------------------
# 3) Diffusion via masking (forward process)
# -----------------------------
T = 10  # diffusion steps
def corrupt(x, t):
    """
    x: [B, L] tokens
    t: [B] integers in [1..T]
    mask probability = t/T (more noise at larger t)
    """
    B, L = x.shape
    mask_prob = (t.float()/T).view(-1,1).expand(B,L)
    # don't mask PAD
    keep_pad = (x == pad_idx)
    noise = torch.rand(B, L, device=x.device)
    x_corrupt = x.clone()
    x_corrupt[(noise < mask_prob) & (~keep_pad)] = mask_idx
    return x_corrupt

# -----------------------------
# 4) Transformer Denoiser
# -----------------------------
class PositionalEncoding(nn.Module):
    def __init__(self, d_model, max_len=512):
        super().__init__()
        pe = torch.zeros(max_len, d_model)
        pos = torch.arange(0, max_len, dtype=torch.float).unsqueeze(1)
        div = torch.exp(torch.arange(0, d_model, 2).float() * (-math.log(10000.0)/d_model))
        pe[:,0::2] = torch.sin(pos*div)
        pe[:,1::2] = torch.cos(pos*div)
        self.register_buffer('pe', pe.unsqueeze(0))  # [1, L, D]
    def forward(self, x):  # x: [B, L, D]
        return x + self.pe[:, :x.size(1), :]

class TransformerDenoiser(nn.Module):
    def __init__(self, vocab_size, d_model=256, nhead=8, num_layers=3, dim_ff=512, dropout=0.1):
        super().__init__()
        self.emb = nn.Embedding(vocab_size, d_model, padding_idx=pad_idx)
        self.time_emb = nn.Embedding(T+1, d_model)  # timestep embedding (1..T)
        self.pos = PositionalEncoding(d_model, max_len=MAX_LEN)
        enc_layer = nn.TransformerEncoderLayer(d_model, nhead, dim_ff, dropout, batch_first=True)
        self.encoder = nn.TransformerEncoder(enc_layer, num_layers=num_layers)
        self.norm = nn.LayerNorm(d_model)
        self.out = nn.Linear(d_model, vocab_size)

    def forward(self, x_tokens, t):
        """
        x_tokens: [B, L] (masked inputs)
        t: [B] timestep
        """
        B, L = x_tokens.shape
        x = self.emb(x_tokens)                               # [B, L, D]
        tvec = self.time_emb(t).unsqueeze(1).expand(B, L, -1)# [B, L, D]
        h = self.pos(x + tvec)                               # add time + position
        key_padding = (x_tokens == pad_idx)                  # [B, L]
        h = self.encoder(h, src_key_padding_mask=key_padding)
        h = self.norm(h)
        logits = self.out(h)                                 # [B, L, V]
        return logits

model = TransformerDenoiser(V).to(device)
opt = optim.AdamW(model.parameters(), lr=1e-3, weight_decay=1e-4)
criterion = nn.CrossEntropyLoss(ignore_index=pad_idx)

# -----------------------------
# 5) Training (ε-free, token denoising)
# -----------------------------
EPOCHS = 50
losses = []

for ep in range(1, EPOCHS+1):
    model.train()
    total = 0.0; steps = 0
    for batch in loader:
        batch = batch.to(device)              # clean tokens (target)
        B, L = batch.shape
        # sample timestep per sample
        t = torch.randint(1, T+1, (B,), device=device)
        x_t = corrupt(batch, t)               # masked input

        logits = model(x_t, t)                # [B, L, V]
        loss = criterion(logits.view(-1, V), batch.view(-1))

        opt.zero_grad()
        loss.backward()
        torch.nn.utils.clip_grad_norm_(model.parameters(), 1.0)
        opt.step()

        total += loss.item(); steps += 1
    losses.append(total/steps)
    print(f"Epoch {ep:02d}/{EPOCHS} | loss: {losses[-1]:.4f}")

# -----------------------------
