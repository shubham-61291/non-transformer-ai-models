# -----------------------------
# 7) Iterative denoising for a sentence (non-autoregressive)
#    Start from a corrupted sentence at high t, then refine down to t=1
# -----------------------------
@torch.no_grad()
def denoise_sentence(sentence:str, start_t:int=8):
    model.eval()
    clean = torch.tensor(encode(sentence), dtype=torch.long, device=device).unsqueeze(0)  # [1, Lc]
    # pad to MAX_LEN
    x = torch.full((1, MAX_LEN), pad_idx, dtype=torch.long, device=device)
    x[0, :clean.size(1)] = clean[0]

    # make a corrupted version at t = start_t
    t = torch.tensor([start_t], device=device)
    x_t = corrupt(x, t)

    print("Clean      :", decode(x[0].tolist()))
    print("Corrupted  :", decode(x_t[0].tolist()))

    # iterative refinement: t=start_t..1
    cur = x_t.clone()
    for step in range(start_t, 0, -1):
        tt = torch.tensor([step], device=device)
        logits = model(cur, tt)
        pred = logits.argmax(dim=-1)  # [1, L]
        # fill only MASK positions (keep already-known tokens)
        mask_positions = (cur == mask_idx)
        cur[mask_positions] = pred[mask_positions]

    recon = decode(cur[0].tolist())
    print("Reconstructed:", recon)
    return recon

