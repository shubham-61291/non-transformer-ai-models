# =========================
# Vanilla GAN on MNIST with Loss Tracking & Plots
# =========================
import torch
import torch.nn as nn
import torch.optim as optim
from torchvision import datasets, transforms
from torch.utils.data import DataLoader
import matplotlib.pyplot as plt

# -----------------------------
# Config
# -----------------------------
batch_size = 128
z_dim = 100         # noise dimension
hidden_dim = 256
epochs = 50
lr = 2e-4
device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
print("Using device:", device)

# -----------------------------
# Data (MNIST, scaled to [-1,1])
# -----------------------------
transform = transforms.Compose([
    transforms.ToTensor(),
    transforms.Normalize((0.5,), (0.5,))  # [-1,1]
])

train_loader = DataLoader(
    datasets.MNIST("./data", train=True, download=True, transform=transform),
    batch_size=batch_size, shuffle=True
)

# -----------------------------
# Models
# -----------------------------
class Generator(nn.Module):
    def __init__(self, z_dim=100, hidden_dim=256, img_dim=28*28):
        super().__init__()
        self.net = nn.Sequential(
            nn.Linear(z_dim, hidden_dim),
            nn.LeakyReLU(0.2),
            nn.Linear(hidden_dim, hidden_dim*2),
            nn.LeakyReLU(0.2),
            nn.Linear(hidden_dim*2, img_dim),
            nn.Tanh()   # output in [-1,1]
        )

    def forward(self, z):
        return self.net(z)

class Discriminator(nn.Module):
    def __init__(self, img_dim=28*28, hidden_dim=256):
        super().__init__()
        self.net = nn.Sequential(
            nn.Linear(img_dim, hidden_dim*2),
            nn.LeakyReLU(0.2),
            nn.Linear(hidden_dim*2, hidden_dim),
            nn.LeakyReLU(0.2),
            nn.Linear(hidden_dim, 1),
            nn.Sigmoid()
        )

    def forward(self, x):
        return self.net(x)

G = Generator(z_dim, hidden_dim).to(device)
D = Discriminator(28*28, hidden_dim).to(device)

# -----------------------------
# Loss & Optimizers
# -----------------------------
criterion = nn.BCELoss()
opt_G = optim.Adam(G.parameters(), lr=lr, betas=(0.5, 0.999))
opt_D = optim.Adam(D.parameters(), lr=lr, betas=(0.5, 0.999))

# -----------------------------
# Training Loop
# -----------------------------
fixed_noise = torch.randn(16, z_dim, device=device)  # for monitoring

losses_D, losses_G = [], []

for epoch in range(1, epochs+1):
    loss_D_epoch, loss_G_epoch = 0.0, 0.0
    num_batches = 0

    for real, _ in train_loader:
        real = real.view(-1, 28*28).to(device)
        batch_size = real.size(0)
        num_batches += 1

        # Labels
        real_labels = torch.ones(batch_size, 1, device=device)
        fake_labels = torch.zeros(batch_size, 1, device=device)

        # -----------------
        # Train Discriminator
        # -----------------
        z = torch.randn(batch_size, z_dim, device=device)
        fake = G(z).detach()

        D_real = D(real)
        D_fake = D(fake)

        loss_D_real = criterion(D_real, real_labels)
        loss_D_fake = criterion(D_fake, fake_labels)
        loss_D = loss_D_real + loss_D_fake

        opt_D.zero_grad()
        loss_D.backward()
        opt_D.step()

        # -----------------
        # Train Generator
        # -----------------
        z = torch.randn(batch_size, z_dim, device=device)
        fake = G(z)
        D_fake = D(fake)

        loss_G = criterion(D_fake, real_labels)  # fool D

        opt_G.zero_grad()
        loss_G.backward()
        opt_G.step()

        # Track running losses
        loss_D_epoch += loss_D.item()
        loss_G_epoch += loss_G.item()

    # Average loss per epoch
    losses_D.append(loss_D_epoch / num_batches)
    losses_G.append(loss_G_epoch / num_batches)

    print(f"Epoch {epoch}/{epochs} | Loss_D={losses_D[-1]:.4f} Loss_G={losses_G[-1]:.4f}")

    # -----------------
    # Show samples every 10 epochs
    # -----------------
    if epoch % 10 == 0:
        with torch.no_grad():
            samples = G(fixed_noise).view(-1,1,28,28)
            samples = (samples+1)/2  # rescale to [0,1] for display
            fig, axes = plt.subplots(2,8,figsize=(12,3))
            for i in range(16):
                ax = axes[i//8, i%8]
                ax.imshow(samples[i,0].cpu(), cmap="gray")
                ax.axis("off")
            plt.show()

# -----------------------------
# Plot losses after training
# -----------------------------
plt.figure(figsize=(8,5))
plt.plot(losses_D, label="Discriminator Loss")
plt.plot(losses_G, label="Generator Loss")
plt.xlabel("Epoch")
plt.ylabel("Loss")
plt.legend()
plt.title("GAN Training Losses")
plt.show()