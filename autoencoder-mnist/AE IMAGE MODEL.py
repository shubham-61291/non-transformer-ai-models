# ===============================
# Step 1: Imports
# ===============================
import torch
import torch.nn as nn
import torch.optim as optim
from torchvision import datasets, transforms
from torch.utils.data import DataLoader
import matplotlib.pyplot as plt

# ===============================
# Step 2: Device
# ===============================
device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
print("Using device:", device)

# ===============================
# Step 3: Dataset (MNIST)
# ===============================
transform = transforms.Compose([
    transforms.ToTensor()   # values already in (0,1) range
])

train_dataset = datasets.MNIST(root='./data', train=True, download=True, transform=transform)
train_loader = DataLoader(train_dataset, batch_size=128, shuffle=True)

test_dataset = datasets.MNIST(root='./data', train=False, download=True, transform=transform)
test_loader = DataLoader(test_dataset, batch_size=128, shuffle=False)

# ===============================
# Step 4: Define Autoencoder
# ===============================
class Autoencoder(nn.Module):
    def __init__(self):
        super(Autoencoder, self).__init__()
        # Encoder
        self.encoder = nn.Sequential(
            nn.Flatten(),
            nn.Linear(28*28, 256),
            nn.ReLU(),
            nn.Linear(256, 128),
            nn.ReLU(),
            nn.Linear(128, 64)   # Bottleneck (latent z)
        )
        # Decoder
        self.decoder = nn.Sequential(
            nn.Linear(64, 128),
            nn.ReLU(),
            nn.Linear(128, 256),
            nn.ReLU(),
            nn.Linear(256, 28*28),
            nn.Sigmoid(),        # Output in (0,1)
            nn.Unflatten(1, (1, 28, 28))
        )

    def forward(self, x):
        z = self.encoder(x)
        out = self.decoder(z)
        return out

# ===============================
# Step 5: Model, Loss, Optimizer
# ===============================
model = Autoencoder().to(device)
criterion = nn.BCELoss()  # Good for (0,1) outputs
optimizer = optim.AdamW(model.parameters(), lr=1e-3, weight_decay=1e-4)

# ===============================
# Step 6: Training Loop
# ===============================
epochs = 20
losses = []

for epoch in range(epochs):
    running_loss = 0.0
    for imgs, _ in train_loader:
        imgs = imgs.to(device)

        # Forward
        outputs = model(imgs)
        loss = criterion(outputs, imgs)

        # Backward
        optimizer.zero_grad()
        loss.backward()
        optimizer.step()

        running_loss += loss.item()

    avg_loss = running_loss / len(train_loader)
    losses.append(avg_loss)
    print(f"Epoch [{epoch+1}/{epochs}], Loss: {avg_loss:.4f}")

# ===============================
# Step 7: Plot Loss Curve
# ===============================
plt.figure(figsize=(8,5))
plt.plot(losses, marker='o')
plt.title("Training Loss Curve")
plt.xlabel("Epoch")
plt.ylabel("Loss")
plt.grid(True)
plt.show()

# ===============================
# Step 8: Visualize Reconstructions
# ===============================
def show_images(model, data_loader):
    model.eval()
    imgs, _ = next(iter(data_loader))
    imgs = imgs.to(device)
    with torch.no_grad():
        recon = model(imgs).cpu()

    fig, axes = plt.subplots(2, 8, figsize=(12,4))
    for i in range(8):
        axes[0,i].imshow(imgs[i].cpu().squeeze(), cmap='gray')
        axes[0,i].set_title("Original")
        axes[0,i].axis('off')
        axes[1,i].imshow(recon[i].squeeze(), cmap='gray')
        axes[1,i].set_title("Reconstructed")
        axes[1,i].axis('off')
    plt.show()

show_images(model, test_loader)