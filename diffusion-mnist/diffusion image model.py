# =========================
# Minimal Diffusion Model on MNIST (with Input/Output Visualization)
# =========================
import torch
import torch.nn as nn
import torch.optim as optim
from torchvision import datasets, transforms
from torch.utils.data import DataLoader
import matplotlib.pyplot as plt

# -----------------------------
# Config
# -----------------------------
device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
batch_size = 128
epochs = 10
lr = 1e-3
img_size = 28
timesteps = 200  # number of diffusion steps

# -----------------------------
# Data
# -----------------------------
transform = transforms.Compose([
    transforms.Resize(img_size),
    transforms.ToTensor(),
    transforms.Normalize((0.5,), (0.5,))  # scale to [-1,1]
])

train_loader = DataLoader(
    datasets.MNIST("./data", train=True, download=True, transform=transform),
    batch_size=batch_size, shuffle=True
)

# -----------------------------
# Noise Scheduler (beta schedule)
# -----------------------------
betas = torch.linspace(1e-4, 0.02, timesteps).to(device)
alphas = 1. - betas
alphas_cumprod = torch.cumprod(alphas, dim=0)

def forward_diffusion(x0, t, noise=None):
    """ Adds noise to image at timestep t """
    if noise is None:
        noise = torch.randn_like(x0)
    sqrt_alpha_cumprod = torch.sqrt(alphas_cumprod[t])[:, None, None, None]
    sqrt_one_minus = torch.sqrt(1 - alphas_cumprod[t])[:, None, None, None]
    return sqrt_alpha_cumprod * x0 + sqrt_one_minus * noise, noise

# -----------------------------
# Simple Denoiser (Tiny U-Net style)
# -----------------------------
class DenoiseModel(nn.Module):
    def __init__(self, img_channels=1):
        super().__init__()
        self.net = nn.Sequential(
            nn.Conv2d(img_channels, 64, 3, padding=1),
            nn.ReLU(),
            nn.Conv2d(64, 128, 3, padding=1),
            nn.ReLU(),
            nn.Conv2d(128, 64, 3, padding=1),
            nn.ReLU(),
            nn.Conv2d(64, img_channels, 3, padding=1),
        )

    def forward(self, x, t):
        # For simplicity, ignore t in this minimal model
        return self.net(x)

model = DenoiseModel().to(device)
opt = optim.Adam(model.parameters(), lr=lr)
criterion = nn.MSELoss()

# -----------------------------
# Training Loop
# -----------------------------
losses = []

for epoch in range(epochs):
    epoch_loss = 0
    for x, _ in train_loader:
        x = x.to(device)

        # Sample random timestep
        t = torch.randint(0, timesteps, (x.size(0),), device=device).long()

        # Forward diffusion (add noise)
        noisy_x, noise = forward_diffusion(x, t)

        # Model predicts noise
        noise_pred = model(noisy_x, t)

        loss = criterion(noise_pred, noise)

        opt.zero_grad()
        loss.backward()
        opt.step()

        epoch_loss += loss.item()

    avg_loss = epoch_loss / len(train_loader)
    losses.append(avg_loss)
    print(f"Epoch {epoch+1}/{epochs} | Loss: {avg_loss:.4f}")

# -----------------------------
# Loss Plot
# -----------------------------
plt.figure(figsize=(8,5))
plt.plot(losses, label="Training Loss")
plt.xlabel("Epoch")
plt.ylabel("Loss (MSE)")
plt.title("Diffusion Model Training Loss")
plt.legend()
plt.show()

# -----------------------------
# Visualize input vs noisy vs denoised
# -----------------------------
@torch.no_grad()
def visualize_noising_and_denoising(model, data_loader, t_step=100, n=6):
    model.eval()
    x, _ = next(iter(data_loader))
    x = x[:n].to(device)

    # Add noise at timestep t_step
    t = torch.tensor([t_step]*n, device=device)
    noisy_x, noise = forward_diffusion(x, t)

    # Predict noise and reconstruct denoised image
    noise_pred = model(noisy_x, t)
    denoised_x = (noisy_x - noise_pred).clamp(-1,1)

    # Rescale to [0,1]
    def rescale(img): return (img.cpu().numpy().transpose(0,2,3,1)+1)/2

    clean_imgs = rescale(x)
    noisy_imgs = rescale(noisy_x)
    denoised_imgs = rescale(denoised_x)

    fig, axes = plt.subplots(n, 3, figsize=(6, 2*n))
    for i in range(n):
        axes[i,0].imshow(clean_imgs[i].squeeze(), cmap="gray"); axes[i,0].set_title("Clean")
        axes[i,1].imshow(noisy_imgs[i].squeeze(), cmap="gray"); axes[i,1].set_title(f"Noisy t={t_step}")
        axes[i,2].imshow(denoised_imgs[i].squeeze(), cmap="gray"); axes[i,2].set_title("Denoised")
        for j in range(3): axes[i,j].axis("off")
    plt.tight_layout(); plt.show()

visualize_noising_and_denoising(model, train_loader, t_step=100, n=6)

# -----------------------------
# Sampling (reverse process)
# -----------------------------
@torch.no_grad()
def sample(model, n=16, show_steps=True):
    model.eval()
    x = torch.randn((n, 1, img_size, img_size), device=device)  # start from noise

    step_imgs = []
    for t in reversed(range(1, timesteps)):
        beta_t = betas[t]
        alpha_t = alphas[t]
        alpha_cumprod_t = alphas_cumprod[t]

        z = torch.randn_like(x) if t > 1 else 0
        noise_pred = model(x, torch.tensor([t]*n, device=device))

        # Reverse update step
        x = (1/torch.sqrt(alpha_t)) * (x - (beta_t/torch.sqrt(1-alpha_cumprod_t))*noise_pred) + torch.sqrt(beta_t)*z

        if show_steps and t % 50 == 0:  # store intermediate steps
            step_imgs.append(x.clone())

    return x, step_imgs

# -----------------------------
# Generate & Show Samples
# -----------------------------
final, steps = sample(model, n=16, show_steps=True)

def show_grid(images, title):
    images = (images.cpu()+1)/2
    fig, axes = plt.subplots(4,4,figsize=(6,6))
    for i in range(16):
        ax = axes[i//4, i%4]
        ax.imshow(images[i,0], cmap="gray")
        ax.axis("off")
    plt.suptitle(title)
    plt.show()

for idx, step in enumerate(steps):
    show_grid(step, f"Samples at t={timesteps-idx*50}")

show_grid(final, "Final Samples")